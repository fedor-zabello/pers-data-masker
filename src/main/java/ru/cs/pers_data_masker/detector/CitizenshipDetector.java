package ru.cs.pers_data_masker.detector;

import org.springframework.stereotype.Component;
import ru.cs.pers_data_masker.domain.PiiType;

/**
 * Детектор гражданства: фраза «гражданин/гражданство ...» + название страны.
 *
 * <p>Название страны ограничено словарём (РФ, Россия, Российская Федерация и
 * распространённые страны), чтобы не ловить фамилии («Гражданин Петров»).
 */
@Component
public class CitizenshipDetector extends AbstractRegexDetector {

    private static final String COUNTRIES =
            "РФ|России|Российская\\s+Федерация|Российской\\s+Федерации|Россия|Беларуси|Беларусь|"
                    + "Белоруссии|Казахстана|Казахстан|Украины|Украина|Узбекистана|Узбекистан|"
                    + "Таджикистана|Таджикистан|Киргизии|Кыргызстана|Кыргызстан|Армении|Армения|"
                    + "Азербайджана|Азербайджан|Грузии|Грузия|Молдовы|Молдавии|Молдова|Молдавия|"
                    + "Латвии|Латвия|Литвы|Литва|Эстонии|Эстония|Германии|Германия|"
                    + "Франции|Франция|Италии|Италия|Испании|Испания|США|Китая|Китай|Индии|Индия|"
                    + "Турции|Турция|Израиля|Израиль|Финляндии|Финляндия|Польши|Польша|Чехии|Чехия|"
                    + "Сербии|Сербия|Болгарии|Болгария";

    private static final String REPUBLICS =
            "Республик[аи]\\s+(?:Казахстан|Беларусь|Узбекистан|Таджикистан|"
                    + "Кыргызстан|Армения|Азербайджан|Молдова|Молдавия|"
                    + "Латвия|Литва|Эстония|Польша|Чехия|Сербия|Болгария|"
                    + "Финляндия|Германия|Франция|Италия|Испания|Китай|Индия|Турция)";

    private static final String CITIZENSHIP_REGEX =
            "(?i)(?:гражданин|гражданство|гражданка)\\s*:?\\s*(?:(?:" + COUNTRIES + ")|(?:" + REPUBLICS + "))";

    public CitizenshipDetector() {
        super(CITIZENSHIP_REGEX, PiiType.CITIZENSHIP.name(), 50);
    }
}